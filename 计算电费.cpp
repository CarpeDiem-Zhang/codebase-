//电价分三个档次，[0, 110]度电，每度电 0.5 元；(110, 210]度电，
//超出 110 部分每度电 0.55 元，超过 210 度电，超出 210 部分每度电 0.70 元，
//一月用电量，请计算出应缴的电费（保留小数点后两位小数）
#include<stdio.h>
int main()
{
	double a,df;//df为电费 
	scanf("%lf" ,&a);
	
	if (a>0&&a<=110)
		printf("%.2f\n" ,df=a*0.5);
	
	else if (a>100&&a<=210)
		printf("%.2f\n" ,df=110*0.5+(a-110)*0.55);
	
	else if (a>210)
		printf("%.2f\n" ,df=110*0.5+100*0.55+(a-210)*0.7);
		
	return 0;
}
